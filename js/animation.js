var s = anime({
    targets: '#s',
    
    backgroundColor: [
        {value:'#ddd', duration: 500 },
        {value:'#FFF', duration: 500}
    ],
    opacity: [0, 1],
    translateX: function(el) {
        return 160;
    },
    translateY: function(el, i) {
        return 50;
    },
    scale: function(el, i, l) {
        return (l - i) + .205;
    },
    rotate: function() { return anime.random(360, 360); },
    borderRadius: ['0', '10px'],
    duration: function() { return anime.random(1800, 1800); },
    delay: function() { return anime.random(100, 100); },

    direction: 'alternate',
    autoplay: false,	

});
